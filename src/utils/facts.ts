/**
 * 「这条线索是**谁**的事」—— 把人物线索从线索池里分出去。
 *
 * ## 为什么要分（2026-11 第十一轮，玩家截图）
 *
 * 玩家的原话是「线索出现频繁」。截图里「线索」页躺着四条：
 * 「小满的住处」「小满没有别的家人」「小满拜师」「炉边女人的警告」——
 * 它们和真正的悬案（「怀表盖内侧的刻字」「柜台上的火漆纸」）混在同一个列表里。
 *
 * 这不是"线索太多"，是**两个不同的东西被塞进了同一个格子**：
 *  - 「怀表盖内侧的刻字」是**待解的疑**：玩家读了它，下一个动作由它决定；
 *  - 「小满的住处」是**已确定的事**：它不进剧情，它进人物档案。
 *
 * 前者该在线索页，后者该在人物卡里。混在一起时两边都变差：
 * 线索页越来越长（于是玩家不再看它），而人物卡里关于这个人的信息
 * 反而是空的（于是模型把他当陌生人写）。
 *
 * 所以这里给出一个**机械判断**：这条 fact 的名字里出现某个在场角色的名字，
 * 它就是那个人的事。然后由 `dossiers` 层收进他的卷宗。
 *
 * ## 为什么只看名字，不看描述
 *
 * 两个理由：
 *  1. 名字是模型**刻意起**的标签（「小满的住处」里那个"小满"不是巧合）；
 *     描述是自然语言，几乎每条线索的描述里都可能顺带提到某个人
 *     （「你问过小满，他说不知道」）—— 那不代表这条线索归他。
 *  2. 判错的代价不对称：把"他的事"漏判成通用线索，玩家多看一眼而已；
 *     把通用线索错判成他的事，那条线索就**从线索页消失了** —— 玩家会找不到。
 *
 * 这条判断是**只用于展示层归类**的，不会删任何数据：一条 fact 无论归了谁，
 * 都仍然在 `facts` 里，只是被折叠到那个人名下显示。
 */

/** 名字短于这个长度不参与匹配：「他」「她」「阿」会命中一切 */
const MIN_NAME_CHARS = 2

/**
 * 这条线索归谁？返回角色的名字，没归属就返回 `null`。
 *
 * 多重命中（名字里同时出现两个角色名）时取**最长的那个**：
 * 「小满的爷爷」里"小满"命中，但若场上真有个叫"小满的爷爷"的存在，
 * 它才是更准确的所有者 —— 具体的那个总比笼统的更对。
 */
export function factOwner(
  factName: string,
  characterNames: readonly string[],
): string | null {
  const name = String(factName || '').trim()
  if (!name) return null

  let best: string | null = null
  for (const raw of characterNames) {
    const who = String(raw || '').trim()
    if (who.length < MIN_NAME_CHARS) continue
    if (!name.includes(who)) continue
    if (!best || who.length > best.length) best = who
  }
  return best
}
