四块大陆的形状本身就是一句遗言。学界公认它们在十万年前是同一块古陆，被一场叫「神战」的灾难撕开、漂成如今的四角——所以看织命星的地图不能只看现在，得看它被撕开之前是什么样。

**地理**这个词在织命星不太好用，因为四块大陆的形状本身就是一场灾难留下的——学界公认它们在十万年前是同一块古陆，被远古「神战」撕开，漂成如今的四角。航海者的航路把它们勉强缝在一起。

西大陆·苍翠之心，别名万森之地、精灵故土、翡翠大陆。它是四大陆中最大的一块，占全球陆地的三成半，八成区域被原始森林覆盖。大陆正中央长着一棵高逾万米的巨树「始祖树·尤格达伦」，根系扎入地下数百公里，枝叶之间自成生态圈，数座精灵城市就建在它的枝杈上。北部温带混交林四季分明，中部热带雨林终年湿热，南部亚热带季风林有短暂旱季；西海岸因寒流经过，形成狭长的迷雾峡湾地带，海族与陆族在那里混居。大陆上有四处地标最常被人挂在嘴边：始祖树尤格达伦本身；中部偏东的泪石丘陵，遍地是能吸魔力的白色巨石，矮人把它们开采用于铸造抗魔装甲；大陆最长的蛇纹河，九曲十八弯，两岸冲积平原是西大陆的粮仓，辉光教廷的圣城就坐在中游；东南角的烬木沼泽，远古神战留下的神血污染了土地，那里的植物长成半血肉的诡异形态，采药人进去十个回来六个。

