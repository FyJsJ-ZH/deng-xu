/**
 * 内置文风库 —— 「怎么写」的可切换选项。
 *
 * ## 为什么要有这个文件
 *
 * 2026-11 第三十轮，玩家丢进来的 SillyTavern 预设（`夏瑾 天琴座 Beta 3.9`）
 * 里其实藏着一整套**文风菜单**：核心文风 12 选 1、附加风格可叠、
 * 基础规范可叠、纠偏器可叠。但它们在 ST 里是"抽屉里的备选"——
 * 只有作者手动勾进 `prompt_order` 的那一条才会被发送。
 *
 * 于是玩家在灯叙这边看到的永远是**一份固定的文风**，
 * 想换就得回 ST 里勾一次、重新导出、重新导入。这不合理：
 * 文风是玩家最容易反悔的东西，它该是一个**可以随时拨的开关**。
 *
 * 所以把这些条目原样搬进代码，变成数据：
 *
 *  - 预设页（全局）从 `id` 选，注入时拼文本 —— 随时换，跨世界，跨局；
 *  - 世界卡编辑器里则是"点一下 → 文本追加进「额外文风要求」"。
 *    两边共用同一份文本，只是**落点**不同：前者是玩家口味，后者是作品设定。
 *
 * ## 四组的关系
 *
 * | 组 | 选择方式 | 说明 |
 * |---|---|---|
 * | `core`  | **单选** | 核心文风，互斥。同时开两条会让模型在两种笔法之间瞎猜 |
 * | `extra` | 多选 | 附加风格，叠在核心文风之上（西式文学 / 轻小说风味） |
 * | `base`  | 多选 | 基础规范，管"描写怎么落地"（白描、细腻度、情感基调） |
 * | `polish`| 多选 | 纠偏器，管"AI 常犯的那个毛病"（升华、对白太顺、全知） |
 *
 * ⚠️ `conflicts` 是**真冲突**，不是风格偏好：`📖 西式文学` 要"轻微翻译腔"，
 * 而 `✅基础文风` 明确"杜绝欧化句式"。两条同时注入，模型只能挑一边，
 * 于是同一份提示词里就出现了自相矛盾的要求。
 */

export type NarrativeStyleGroup = 'core' | 'extra' | 'base' | 'polish'

export interface NarrativeStyleOption {
  /** 稳定 id：写进存档、世界卡里带上它 */
  id: string
  /** 显示名（沿用原作者的名字，玩家在 ST 里见过这些词） */
  name: string
  group: NarrativeStyleGroup
  /** 注入用的正文 */
  text: string
  /** 一句话说清它**擅长**什么 —— 选的时候要知道自己在选什么 */
  note: string
  /** 与哪些 id 直接打架（互斥或语义矛盾） */
  conflicts?: string[]
}

