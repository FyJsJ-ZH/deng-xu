/** 按 id 取一条 */
export function styleById(id: string): NarrativeStyleOption | undefined {
  return NARRATIVE_STYLES.find(s => s.id === id)
}

/** 分组取（UI 与渲染共用同一套顺序） */
export function stylesOf(group: NarrativeStyleGroup): NarrativeStyleOption[] {
  return NARRATIVE_STYLES.filter(s => s.group === group)
}

/**
 * 一套文风选择。
 *
 * `core` 是单一 id（`''` = 不选），其余是多选数组 ——
 * 这个形状本身就说明了互斥关系，UI 不必再单独记账。
 */
export interface StyleChoice {
  core: string
  extra: string[]
  base: string[]
  polish: string[]
}

export const EMPTY_STYLE_CHOICE: StyleChoice = { core: '', extra: [], base: [], polish: [] }

/** 选择里有没有东西（空选择不该让"已启用"三个字骗人） */
export function isEmptyStyleChoice(c: StyleChoice | null | undefined): boolean {
  if (!c) return true
  return !c.core && !c.extra.length && !c.base.length && !c.polish.length
}

/** 选中项的全部 id（按注入顺序：核心 → 附加 → 基础 → 纠偏） */
export function chosenStyleIds(c: StyleChoice): string[] {
  return [
    ...(c.core ? [c.core] : []),
    ...c.extra,
    ...c.base,
    ...c.polish,
  ]
}
